# tests/test_migration_transformer.py
import ast
from unittest.mock import mock_open, patch

import pytest
from django.test import override_settings

from postgres_schema.management.commands.makemigrations import (
    Command,
    MigrationTransformer,
)


@pytest.fixture
def transformer():
    return MigrationTransformer(operation_class="RunInTemplate")


@pytest.fixture
def sample_migration():
    return """
from django.db import migrations, models

class Migration(migrations.Migration):
    dependencies = []
    operations = [
        migrations.CreateModel(
            name='TestModel',
            fields=[
                ('id', models.AutoField(primary_key=True)),
            ],
        ),
        migrations.AddField(
            model_name='TestModel',
            name='field',
            field=models.CharField(max_length=100),
        ),
    ]
"""


def test_basic_transformation(transformer, sample_migration):
    tree = ast.parse(sample_migration)
    result = transformer.visit(tree)
    transformed = ast.unparse(result)

    assert "RunInTemplate(migrations.CreateModel" in transformed
    assert "RunInTemplate(migrations.AddField" in transformed


def test_selective_transformation():
    """Test only transforms operations for configured apps"""
    before = """
operations = [
    migrations.CreateModel(name='AppModel', fields=[]),
    migrations.RunPython(some_function)
]
    """
    after = ast.unparse(MigrationTransformer("RunInTemplate").visit(ast.parse(before)))
    assert "RunInTemplate" in after
    assert "RunPython(some_function)" in after  # Unchanged


def test_preserves_operation_order(transformer):
    """Ensures operation order remains intact after transformation"""
    ops = """
operations = [
    migrations.CreateModel(name='First', fields=[]),
    migrations.CreateModel(name='Second', fields=[]),
]
    """
    result = ast.unparse(transformer.visit(ast.parse(ops)))
    first_pos = result.find("First")
    second_pos = result.find("Second")
    assert first_pos < second_pos


# Edge cases
def test_empty_operations():
    assert (
        ast.unparse(MigrationTransformer([]).visit(ast.parse("operations = []")))
        == "operations = []"
    )


