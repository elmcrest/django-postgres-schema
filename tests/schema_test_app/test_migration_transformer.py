@override_settings(POSTGRES_SCHEMA_APPS=("tenant_app",))
@patch("builtins.open", new_callable=mock_open)
def test_transform_migration_apps(mock_file, migration_content):
    mock_file.return_value.__enter__.return_value.read.return_value = migration_content

    command = Command()
    command._transform_migration("fake/tenant_app/migrations/0002_test.py")

    # Verify write contains wrapped operations
    written_content = mock_file().write.call_args[0][0]
    assert "RunInTemplate(migrations.CreateModel" in written_content
    assert "from postgres_schema.operations import RunInTemplate" in written_content


